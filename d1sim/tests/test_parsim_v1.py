def test_adapter_example_events_reproduce(tmp_path):
    """examples/events_R*.jsonl must be regenerated byte-for-byte by the CLI (same seed 1 · window 120)."""
    import hashlib
    import os
    from d1sim.parsim_v1 import adapter
    ex = os.path.join(os.path.dirname(adapter.__file__), 'examples')
    for rule in ('R2', 'R3', 'R4', 'R5'):
        out = tmp_path / f'events_{rule}.jsonl'
        assert adapter.main(['run', '--requests', os.path.join(ex, 'requests_192_200ms.json'), '--rule', rule,
                             '--start', os.path.join(ex, 'start_30p5.json'), '--seed', '1', '--window', '120', '--out', str(out)]) == 0
        want = hashlib.sha256(open(os.path.join(ex, f'events_{rule}.jsonl'), 'rb').read()).hexdigest()
        assert hashlib.sha256(out.read_bytes()).hexdigest() == want, rule
